/* Bakes biomarkers-data.js (the list on the What-we-test page) from the panel data of the preview site (tools/source/panel-data.js, male variant).   run: node tools/bake-biomarkers.js */
const fs = require('fs'); global.window = {}; require('./source/panel-data.js'); const P = window.PANEL;
const title = s => s.replace(/\b[a-z]/g, c => c.toUpperCase());
const systems = P.systems.map(s => ({
  id: s.id, name: title(s.name), intro: s.intro,
  markers: s.markers.filter(m => m.sex !== 'f').map(m => { const o = { n: m.n, u: m.u, w: m.w || '' }; if (m.readings) o.r = m.readings; if (m.count) o.c = m.count; return o; })
}));
const total = systems.reduce((a, s) => a + s.markers.reduce((b, m) => b + (m.c || 1), 0), 0);
fs.writeFileSync(__dirname + '/../biomarkers-data.js', '/* generated by tools/bake-biomarkers.js */\nwindow.BIOMARKERS = ' + JSON.stringify({ total, systems }) + ';\n');
console.log(total, systems.map(s => s.name + ' ' + s.markers.length).join(', '));
